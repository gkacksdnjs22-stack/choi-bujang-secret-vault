-- 새 임시 가상 메모만 사용하고 모든 변경을 롤백합니다.
begin;
create temporary table preview_results(check_name text,passed boolean) on commit drop;
do $$
declare p public.principal_bindings%rowtype; target uuid:=gen_random_uuid();
  v jsonb; audit_count bigint; denied boolean; original_rows text;
begin
  select * into p from public.principal_bindings where enabled and expires_at>now() limit 1;
  if not found then raise exception 'active_binding_required'; end if;
  select coalesce(jsonb_agg(to_jsonb(n) order by public_id)::text,'[]') into original_rows from public.notes n;
  select count(*) into audit_count from public.note_recovery_audit;
  insert into public.notes(public_id,owner_id,title,content) values(target,p.user_id,'virtual preview','virtual original');
  update public.notes set title='virtual changed title',content='virtual changed' where public_id=target;
  v:=public.preview_private_note_recovery(target,p.user_id,p.class_id,p.project_id,p.subject_id,p.device_id);
  insert into preview_results values('preview_version_and_fields',v->>'verified'='true' and length(v->>'version')=64 and v->'changedFields'='["title","content"]'::jsonb);
  insert into preview_results select 'preview_does_not_restore',content='virtual changed' from public.notes where public_id=target;
  insert into preview_results select 'preview_does_not_audit',count(*)=audit_count from public.note_recovery_audit;
  update public.notes set content='virtual concurrent edit' where public_id=target;
  denied:=false;
  begin perform public.restore_verified_private_note(target,p.user_id,p.class_id,p.project_id,p.subject_id,p.device_id,v->>'version',v->>'stateVersion');
  exception when others then if sqlerrm='restore_rejected' then denied:=true; else raise; end if; end;
  insert into preview_results values('changed_target_rejected',denied);
  v:=public.preview_private_note_recovery(target,p.user_id,p.class_id,p.project_id,p.subject_id,p.device_id);
  update public.note_recovery_snapshots set title='virtual changed snapshot' where public_id=target;
  denied:=false;
  begin perform public.restore_verified_private_note(target,p.user_id,p.class_id,p.project_id,p.subject_id,p.device_id,v->>'version',v->>'stateVersion');
  exception when others then if sqlerrm='restore_rejected' then denied:=true; else raise; end if; end;
  insert into preview_results values('changed_snapshot_rejected',denied);
  update public.note_recovery_snapshots set title='virtual preview',content_sha256='invalid' where public_id=target;
  denied:=false;
  begin perform public.preview_private_note_recovery(target,p.user_id,p.class_id,p.project_id,p.subject_id,p.device_id);
  exception when others then if sqlerrm='restore_rejected' then denied:=true; else raise; end if; end;
  insert into preview_results values('invalid_snapshot_rejected',denied);
  update public.note_recovery_snapshots set content_sha256=encode(extensions.digest(content,'sha256'),'hex') where public_id=target;
  v:=public.preview_private_note_recovery(target,p.user_id,p.class_id,p.project_id,p.subject_id,p.device_id);
  perform public.restore_verified_private_note(target,p.user_id,p.class_id,p.project_id,p.subject_id,p.device_id,v->>'version',v->>'stateVersion');
  insert into preview_results select 'verified_restore_succeeds',title='virtual preview' and content='virtual original' from public.notes where public_id=target;
  denied:=false;
  begin perform public.preview_private_note_recovery(target,gen_random_uuid(),p.class_id,p.project_id,p.subject_id,p.device_id);
  exception when others then if sqlerrm='restore_rejected' then denied:=true; else raise; end if; end;
  insert into preview_results values('other_actor_rejected',denied);
  denied:=false;
  begin perform public.preview_private_note_recovery(gen_random_uuid(),p.user_id,p.class_id,p.project_id,p.subject_id,p.device_id);
  exception when others then if sqlerrm='restore_rejected' then denied:=true; else raise; end if; end;
  insert into preview_results values('missing_snapshot_rejected',denied);
  insert into preview_results select 'other_notes_preserved',coalesce(jsonb_agg(to_jsonb(n) order by public_id)::text,'[]')=original_rows from public.notes n where public_id<>target;
  insert into preview_results select 'only_success_audited',count(*)=audit_count+1 from public.note_recovery_audit;
  if exists(select 1 from preview_results where passed is not true) then raise exception 'preview_test_failed'; end if;
end $$;
select * from preview_results order by check_name;
rollback;
